class Solution:
    def solveNQueens(self, n: int) -> list[list[str]]:
        if n == 1:
            return [["Q"]]
        if n <= 3:
            return []

        positions = [-1] * n
        ret = []
        positions_unused = set(range(n))

        def helper(index: int):
            nonlocal positions
            nonlocal positions_unused
            if index == n:
                ret.append(
                    [
                        "".join(["."] * position + ["Q"] + ["."] * (n - 1 - position))
                        for position in positions
                    ]
                )
                return
            for pos in range(n):
                if pos in positions_unused:
                    if any(
                        positions[i] - i == pos - index
                        or positions[i] + i == pos + index
                        for i in range(index)
                    ):
                        continue
                    positions_unused.remove(pos)
                    positions[index] = pos
                    helper(index + 1)
                    positions_unused.add(pos)

        helper(0)
        # print(ret)
        return ret


