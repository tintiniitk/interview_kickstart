class Solution:
    def search(self, nums: list[int], target: int) -> bool:
        # shortcut
        # return nums.count(target) > 0

        n = len(nums)
        if n == 1:
            return nums[0] == target

        l, r = 0, n - 1
        while l <= r:
            m = (l + r) // 2
            if nums[m] == target:
                return True
            if nums[l] == nums[m] == nums[r]:
                l, r = l + 1, r - 1
                continue
            if nums[m] < nums[l]:
                # right side is sorted.
                if nums[m] < target <= nums[r]:
                    l = m + 1
                else:
                    r = m - 1
            else:
                # left side is sorted
                if nums[m] > target >= nums[l]:
                    r = m - 1
                else:
                    l = m + 1
        return False


